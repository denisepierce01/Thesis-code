        ];
    end
    
    % If no size is requested, default to a crisp 256 levels
    if nargin < 1, N = 256; end
    
    % Linearly interpolate the control points to the requested map size N
    old_X = linspace(0, 1, size(base_map, 1));
    new_X = linspace(0, 1, N);
    cmap = interp1(old_X, base_map, new_X, 'linear');
end