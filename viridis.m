function cmap = viridis(N)
    % Standard 256-color Viridis RGB matrix data
    persistent base_map;
    if isempty(base_map)
        % Sampled control points of the exact Viridis color profile
        base_map = [
            0.267004, 0.004874, 0.329415;
            0.268510, 0.057375, 0.354387;
